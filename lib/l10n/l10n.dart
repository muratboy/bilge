library;

class L {
  /// Etkin dil kodu: 'tr' ya da 'en'. Ayarlardan ya da cihaz dilinden belirlenir.
  static String code = 'tr';
  static const supported = ['tr', 'en'];

  static Map<String, String> get table => code == 'en' ? en : tr;

  static String t(String key, [Map<String, Object?> args = const {}]) {
    var s = table[key] ?? tr[key] ?? key;
    args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }

  /// "a|b|c" biçimindeki çok seçenekli metinler (gün adları gibi).
  static List<String> list(String key) => t(key).split('|');
}

String t(String key, [Map<String, Object?> args = const {}]) => L.t(key, args);

